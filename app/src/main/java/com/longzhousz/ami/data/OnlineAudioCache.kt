package com.longzhousz.ami.data

import android.content.ContentValues
import android.content.Context
import android.database.sqlite.SQLiteDatabase
import android.database.sqlite.SQLiteOpenHelper
import android.media.MediaMetadataRetriever
import com.longzhousz.ami.core.AudioQuality
import com.longzhousz.ami.core.cloudMediaUrl
import kotlinx.coroutines.CancellationException
import java.io.File
import java.net.HttpURLConnection
import java.net.URI
import java.security.MessageDigest
import java.util.UUID

/** Complete, disposable copies only. Imported music and its database never enter this store. */
internal class OnlineAudioCache(
    context: Context,
    name: String = "online-audio",
    private val budget: () -> Long = { DEFAULT_BUDGET },
    private val reserve: Long = 1024L * 1024 * 1024,
    private val open: (String) -> HttpURLConnection = { URI(it).toURL().openConnection() as HttpURLConnection },
) : SQLiteOpenHelper(context, File(context.noBackupFilesDir, "$name.db").path, null, 1) {
    private val dir = File(context.cacheDir, name)
    private var ownerLoaded = false
    private var owner: String? = null
    private var downloading: File? = null
    @Volatile var playingId: String? = null
    @Volatile var trimPending: Boolean = false
        private set
    data class Candidate(val id: String, val duration: Long)
    data class Hit(val file: File, val quality: AudioQuality)
    override fun onCreate(db: SQLiteDatabase) {
        db.execSQL("CREATE TABLE owner (scope TEXT)")
        db.execSQL("CREATE TABLE audio (id TEXT PRIMARY KEY,t1 INTEGER NOT NULL,t2 INTEGER NOT NULL,t3 INTEGER NOT NULL,duration INTEGER NOT NULL,file TEXT,bytes INTEGER NOT NULL DEFAULT 0,level TEXT,codec TEXT,bitrate INTEGER,retry INTEGER NOT NULL DEFAULT 0)")
    }
    override fun onUpgrade(db: SQLiteDatabase, oldVersion: Int, newVersion: Int) = Unit
    @Synchronized fun scope(): String? {
        if (!ownerLoaded) {
            owner = readableDatabase.rawQuery("SELECT scope FROM owner LIMIT 1", null).use { if (it.moveToFirst()) it.getString(0) else null }
            ownerLoaded = true
        }
        return owner
    }
    @Synchronized fun switchAccount(account: String?) {
        if (scope() == account) return
        dir.mkdirs()
        writableDatabase.beginTransaction()
        try {
            writableDatabase.delete("audio", null, null); writableDatabase.delete("owner", null, null)
            if (account != null) writableDatabase.insertOrThrow("owner", null, ContentValues().apply { put("scope", account) })
            // All names in this private directory are generated by this class.
            dir.listFiles()?.forEach { it.delete() }
            writableDatabase.setTransactionSuccessful()
        } finally { writableDatabase.endTransaction() }
        owner = account; ownerLoaded = true
    }
    @Synchronized fun record(account: String, id: String, duration: Long, now: Long): Boolean {
        if (scope() != account) return false
        val older = readableDatabase.rawQuery("SELECT t1,t2 FROM audio WHERE id=?", arrayOf(id)).use {
            if (it.moveToFirst()) it.getLong(0) to it.getLong(1) else 0L to 0L
        }
        val values = ContentValues().apply { put("t1", now); put("t2", older.first); put("t3", older.second); put("duration", duration) }
        if (writableDatabase.update("audio", values, "id=?", arrayOf(id)) == 0) {
            values.put("id", id); writableDatabase.insertOrThrow("audio", null, values)
        }
        // Only a bounded recent history is needed; cached rows remain governed by the byte/age budget.
        writableDatabase.execSQL("DELETE FROM audio WHERE file IS NULL AND id NOT IN (SELECT id FROM audio ORDER BY t1 DESC LIMIT 2000)")
        return older.second >= now - WEEK
    }
    @Synchronized fun candidates(account: String, now: Long): List<Candidate> {
        if (scope() != account) return emptyList()
        return readableDatabase.rawQuery("SELECT id,duration FROM audio WHERE t3>=? AND file IS NULL AND retry<=? ORDER BY t1 DESC LIMIT 2",
            arrayOf((now - WEEK).toString(), now.toString())).use { rows -> buildList { while (rows.moveToNext()) add(Candidate(rows.getString(0), rows.getLong(1))) } }
    }
    @Synchronized fun get(account: String, id: String, now: Long): Hit? {
        if (scope() != account) return null
        val hit = readableDatabase.rawQuery("SELECT file,bytes,level,codec,bitrate,t1 FROM audio WHERE id=? AND file IS NOT NULL", arrayOf(id)).use {
            if (!it.moveToFirst()) return null
            val file = ownedFile(it.getString(0))
            if (file == null || !file.isFile || file.length() != it.getLong(1) || file.length() == 0L || it.getLong(5) < now - WEEK) null
            else Hit(file, AudioQuality("netease:$id", it.getString(2), it.getString(3), it.getInt(4).takeIf { br -> br > 0 }, cached = true))
        }
        if (hit == null) invalidate(account, id)
        return hit
    }
    @Synchronized fun invalidate(account: String, id: String) {
        if (scope() != account) return
        readableDatabase.rawQuery("SELECT file FROM audio WHERE id=?", arrayOf(id)).use { if (it.moveToFirst()) ownedFile(it.getString(0))?.delete() }
        writableDatabase.execSQL("UPDATE audio SET file=NULL,bytes=0,retry=? WHERE id=?", arrayOf<Any>(System.currentTimeMillis() + DAY, id))
    }
    @Synchronized fun failed(account: String, id: String, now: Long) {
        if (scope() == account) writableDatabase.execSQL("UPDATE audio SET retry=? WHERE id=?", arrayOf<Any>(now + DAY, id))
    }
    @Synchronized fun cleanup(now: Long, incoming: Long = 0, diskIncoming: Long = incoming, active: () -> Boolean = { true }): Boolean {
        if (!active()) return false
        val limit = budget()
        data class Stored(val id: String, val file: File?, val bytes: Long, val heard: Long)
        val files = readableDatabase.rawQuery("SELECT id,file,bytes,t1 FROM audio WHERE file IS NOT NULL ORDER BY t1", null).use { rows ->
            buildList { while (rows.moveToNext()) add(Stored(rows.getString(0), ownedFile(rows.getString(1)), rows.getLong(2), rows.getLong(3))) }
        }
        val referenced = files.mapNotNull { it.file?.name }.toSet()
        // Process death can leave a partial or a renamed-but-uncommitted file. Reclaim it on the
        // next visit, while preserving the one download currently owned by this process.
        dir.listFiles()?.forEach { if (!active()) return false; if (it.name !in referenced && it != downloading) it.delete() }
        var total = files.sumOf { it.bytes }
        files.forEach {
            if (!active()) return false
            if (it.id != playingId && (it.heard < now - WEEK || it.file?.isFile != true || total + incoming > limit || dir.usableSpace < reserve + diskIncoming)) {
                if (it.file == null || !it.file.exists() || it.file.delete()) {
                    total -= it.bytes
                    writableDatabase.execSQL("UPDATE audio SET file=NULL,bytes=0 WHERE id=?", arrayOf(it.id))
                }
            }
        }
        writableDatabase.delete("audio", "t1<? AND file IS NULL", arrayOf((now - WEEK).toString()))
        trimPending = total > limit
        return total + incoming <= limit && dir.usableSpace >= reserve + diskIncoming
    }
    /** Download outside the DB lock; publish one verified file atomically, or leave no playable entry. */
    fun download(account: String, candidate: Candidate, audio: NeteaseAudio, now: Long, active: () -> Boolean) {
        require(audio.bytes in 1..minOf(budget(), MAX_FILE)) { "Unbounded audio" }
        fun checkActive() { if (!active()) throw CancellationException("Cache work deferred") }
        require(scope() == account)
        checkActive()
        dir.mkdirs()
        val room = cleanup(now, audio.bytes, active = active)
        checkActive()
        check(room) { "Cache budget" }
        val part = File(dir, UUID.randomUUID().toString() + ".part")
        synchronized(this) { downloading = part }
        var connection: HttpURLConnection? = null
        try {
            val http = open(cloudMediaUrl(audio.url)).also { connection = it }
            http.instanceFollowRedirects = false; http.connectTimeout = 7000; http.readTimeout = 15000
            http.setRequestProperty("Accept-Encoding", "identity")
            require(http.responseCode == 200)
            require(http.contentLengthLong == -1L || http.contentLengthLong == audio.bytes)
            val digest = MessageDigest.getInstance("MD5")
            val started = android.os.SystemClock.elapsedRealtime()
            var size = 0L
            http.inputStream.use { input -> part.outputStream().use { output ->
                val buffer = ByteArray(64 * 1024)
                while (true) {
                    checkActive()
                    check(android.os.SystemClock.elapsedRealtime() - started < 180_000)
                    val count = input.read(buffer); if (count < 0) break
                    size += count; require(size <= audio.bytes)
                    output.write(buffer, 0, count); digest.update(buffer, 0, count)
                }
                output.fd.sync()
            } }
            require(size == audio.bytes)
            if (audio.md5 != null) require(digest.digest().joinToString("") { "%02x".format(it) } == audio.md5)
            val media = MediaMetadataRetriever()
            try {
                media.setDataSource(part.path)
                val duration = media.extractMetadata(MediaMetadataRetriever.METADATA_KEY_DURATION)?.toLongOrNull() ?: 0
                require(duration > 0 && (candidate.duration <= 0 || kotlin.math.abs(duration - candidate.duration) <= 3000))
            } finally { media.release() }
            synchronized(this) {
                checkActive()
                check(scope() == account && cleanup(now, size, diskIncoming = 0, active = active))
                checkActive()
                val name = UUID.randomUUID().toString() + ".audio"
                check(part.renameTo(File(dir, name)))
                val values = ContentValues().apply {
                    put("file", name); put("bytes", size); put("level", audio.level); put("codec", audio.codec); put("bitrate", audio.bitrate); put("retry", 0)
                }
                if (writableDatabase.update("audio", values, "id=? AND file IS NULL", arrayOf(candidate.id)) != 1) File(dir, name).delete()
            }
        } finally {
            connection?.disconnect(); part.delete()
            synchronized(this) { if (downloading == part) downloading = null }
        }
    }
    private fun ownedFile(name: String?): File? = name?.takeIf { it.matches(Regex("[a-f0-9-]{36}\\.audio")) }?.let { File(dir, it) }
    companion object {
        const val DEFAULT_BUDGET = 512L * 1024 * 1024
        val LIMITS = listOf(256L, 512L, 1024L, 2048L, 4096L, 8192L).map { it * 1024 * 1024 }
        const val DAY = 86_400_000L
        const val WEEK = 7 * DAY
        const val MAX_FILE = 256L * 1024 * 1024
    }
}
